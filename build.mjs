// Tiny static build: wraps src/pages/*.html in the shared layout + partials → dist/
// Usage: node build.mjs
import { readFileSync, writeFileSync, mkdirSync, readdirSync, cpSync, rmSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";
import vm from "node:vm";

const SITE = "https://www.ghveiligfietsen.nl"; // TODO: real domain
const VER = Date.now().toString(36); // cache-busting stamp for CSS/JS links
const root = dirname(fileURLToPath(import.meta.url));
const src = join(root, "src"), out = join(root, "dist");
const read = (p) => readFileSync(join(src, p), "utf8");

// Load shop config (same file the browser uses)
const ctx = { window: {} };
vm.runInNewContext(read("assets/js/config.js"), ctx);
const GH = ctx.window.GH;

const dayNames = ["Sunday", "Monday", "Tuesday", "Wednesday", "Thursday", "Friday", "Saturday"];
const schema = {
  "@context": "https://schema.org",
  "@type": "BicycleStore",
  "@id": `${SITE}/#store`,
  name: GH.name,
  description: "Nieuwe en tweedehands fietsen, fietsreparatie en fietsverhuur in Utrecht centrum. Gratis vervangende fiets tijdens reparatie, 10% studentenkorting, fietsen vanaf €99.",
  url: SITE,
  telephone: GH.phoneIntl,
  image: `${SITE}/assets/img/og.jpg`,
  logo: `${SITE}/assets/img/logo.svg`,
  priceRange: "€€",
  currenciesAccepted: "EUR",
  paymentAccepted: "Cash, Debit Card, Credit Card, Apple Pay, Google Pay",
  address: { "@type": "PostalAddress", streetAddress: GH.street, postalCode: GH.postcode.replace(" ", ""), addressLocality: GH.city, addressCountry: "NL" },
  geo: { "@type": "GeoCoordinates", latitude: 52.0937, longitude: 5.1218 }, // TODO: verify exact pin
  areaServed: "Utrecht",
  openingHoursSpecification: Object.entries(GH.hours).filter(([, h]) => h).map(([d, h]) => ({
    "@type": "OpeningHoursSpecification", dayOfWeek: dayNames[d], opens: h[0], closes: h[1]
  })),
  makesOffer: ["Tweedehands fietsen", "Nieuwe fietsen", "Fietsreparatie", "Fietsverhuur", "Inkoop fietsen"].map((n) => ({ "@type": "Offer", itemOffered: { "@type": "Service", name: n } })),
  sameAs: Object.values(GH.socials).filter(Boolean)
};

// ---- Logo (Figma "Layer_1", node 11:2) → stacked lockup, inline symbols, favicon ----
// logo-figma.svg: path 1 = wordmark (Geom Medium, outlined), paths 2–3 = icon (G + bike).
const figmaPaths = [...read("assets/img/logo-figma.svg").matchAll(/<path[^>]*\/>/g)].map((m) => m[0]);
const wordPaths = figmaPaths.slice(0, 1), iconPaths = figmaPaths.slice(1);
const FULL_VB = "18 0 3575 1512", ICON_VB = "953 0 1848 1112"; // tight boxes around the artwork
const recolor = (p, c) => p.replace(/fill="black"/g, `fill="${c}"`);
const svgFile = (vb, list, c) => `<!-- generated by build.mjs from logo-figma.svg -->\n<svg xmlns="http://www.w3.org/2000/svg" viewBox="${vb}" role="img" aria-label="GH Veilig Fietsen">\n${list.map((p) => recolor(p, c)).join("\n")}\n</svg>\n`;
writeFileSync(join(src, "assets/img/logo.svg"), svgFile(FULL_VB, [...iconPaths, ...wordPaths], "#0D0D0D"));
writeFileSync(join(src, "assets/img/logo-white.svg"), svgFile(FULL_VB, [...iconPaths, ...wordPaths], "#FFFFFF"));
writeFileSync(join(src, "assets/img/logo-icon.svg"), svgFile(ICON_VB, iconPaths, "#0D0D0D"));
// favicon: white icon centred on a black rounded square (icon is 1848 × 1112)
writeFileSync(join(src, "assets/img/favicon.svg"),
  `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 64 64"><rect width="64" height="64" rx="12" fill="#0d0d0d"/><g transform="translate(5 15.74) scale(.02922) translate(-953.6 0)">${iconPaths.map((p) => recolor(p, "#FFFFFF")).join("")}</g></svg>\n`);
const logoSymbols = `<symbol id="logo-icon" viewBox="${ICON_VB}">${iconPaths.map((p) => recolor(p, "currentColor")).join("")}</symbol><symbol id="logo-full" viewBox="${FULL_VB}">${[...iconPaths, ...wordPaths].map((p) => recolor(p, "currentColor")).join("")}</symbol>`;

rmSync(out, { recursive: true, force: true });
mkdirSync(out, { recursive: true });
cpSync(join(src, "assets"), join(out, "assets"), { recursive: true });

const layout = read("layout.html");
const partials = Object.fromEntries(readdirSync(join(src, "partials")).map((f) => [f.replace(".html", ""), read(`partials/${f}`).replace("<!--logo-symbols-->", logoSymbols)]));
const esc = (s) => s.replace(/&/g, "&amp;").replace(/"/g, "&quot;");
const urls = [];

for (const file of readdirSync(join(src, "pages")).filter((f) => f.endsWith(".html"))) {
  let page = read(`pages/${file}`);
  const m = page.match(/^<!--meta\s*([\s\S]*?)-->/);
  const meta = JSON.parse(m[1]);
  page = page.slice(m[0].length).trim();
  const url = file === "index.html" ? `${SITE}/` : `${SITE}/${file}`;
  urls.push(url);
  let html = layout
    .replace(/{{> (\w+)}}/g, (_, n) => partials[n])
    .replace("{{content}}", () => page)
    .replace(/{{title}}/g, esc(meta.title))
    .replace(/{{ver}}/g, VER)
    .replace(/{{titleEn}}/g, esc(meta.titleEn))
    .replace(/{{desc}}/g, esc(meta.desc))
    .replace(/{{url}}/g, url)
    .replace(/{{site}}/g, SITE)
    .replace("{{schema}}", () => JSON.stringify(meta.schemaExtra ? [schema, ...meta.schemaExtra] : schema));
  html = html.replace(new RegExp(`data-nav="${meta.nav}"`), `data-nav="${meta.nav}" aria-current="page"`);
  writeFileSync(join(out, file), html);
  console.log("built", file);
}

writeFileSync(join(out, "sitemap.xml"), `<?xml version="1.0" encoding="UTF-8"?>\n<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">\n${urls.map((u) => `  <url><loc>${u}</loc></url>`).join("\n")}\n</urlset>\n`);
writeFileSync(join(out, "robots.txt"), `User-agent: *\nAllow: /\nSitemap: ${SITE}/sitemap.xml\n`);
console.log("done →", out);
